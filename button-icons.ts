export function isButtonLit(id: string, state: boolean): boolean {
  return id === 'lock' ? !state : state
}
// state 为 true 表示车辆处于“开启 / 已锁 / 已运行”一侧的状态。
// lineWidth 对全部 10 枚图标生效：5 枚描边图标直接改 stroke-width，
// 尾门 / 车窗 / 空调 / 冷车 / 座椅加热 五枚实心图标走 fillStroke() 的同色加粗（见上）。
export function buttonIconSVG(id: string, state: boolean, color: string, lineWidth = 1.7, tight = false): string {
  const paint = color || '#FFFFFF'
  // 尾门：state 为 true（尾门已开 → 激活色）用掀起的那张，false（已关 → 未激活色）用闭合的那张。
  if (id === 'trunk') {
    const stroke = fillStroke(lineWidth, FILL_BASE_TRUNK, TRUNK_UNIT)
    return filledTrunk(paint, state ? TRUNK_RAISED : TRUNK_CLOSED, stroke, fillViewBox(TRUNK_VIEWBOX, TRUNK_UNIT, stroke, tight))
  }
  // 车窗：按用户反馈两态对调 —— state 为 true（车窗已开）用 WINDOW_ACTIVE 那张，false（已关闭）用 WINDOW_IDLE 那张。
  if (id === 'window') {
    const stroke = fillStroke(lineWidth, FILL_BASE_WINDOW, WINDOW_UNIT)
    return filled(fillViewBox(WINDOW_VIEWBOX, WINDOW_UNIT, stroke, tight), paint, state ? WINDOW_ACTIVE : WINDOW_IDLE, stroke)
  }
  // 空调：两态图形完全相同（用户给的两张 SVG 一致），只靠颜色区分。
  if (id === 'ac') {
    const stroke = fillStroke(lineWidth, FILL_BASE_AC, AC_UNIT)
    return filled(fillViewBox(AC_VIEWBOX, AC_UNIT, stroke, tight), paint, AC_FAN, stroke)
  }
  // 冷车：同样两态图形一致，只靠颜色区分。
  if (id === 'cool') {
    const stroke = fillStroke(lineWidth, FILL_BASE_COOL, COOL_UNIT)
    return filled(fillViewBox(COOL_VIEWBOX, COOL_UNIT, stroke, tight), paint, [COOL_SNOW], stroke)
  }
  // 座椅加热：两态图形按用户要求对调 —— state 为 true（已开启）用 SEAT_OFF 那张，false（已关闭）用 SEAT_ON 那张。
  if (id === 'seat') {
    const stroke = fillStroke(lineWidth, FILL_BASE_SEAT, SEAT_UNIT)
    return filled(fillViewBox(SEAT_VIEWBOX, SEAT_UNIT, stroke, tight), paint, state ? SEAT_OFF : SEAT_ON, stroke)
  }
  return wrap(paint, iconBody(id, state, paint), lineWidth, tight)
}

// 奥迪四环：单环直径 100，圆心距 75（相邻环重叠 25%），描边 11（约直径 11%）。
// 整体宽高比 325 : 100，与官方标志一致，可直接放进原车辆图片的位置。
const RING_D = 100
const RING_GAP = 75
const RING_STROKE = 11
const AUDI_LOGO_RATIO = (3 * RING_GAP + RING_D) / RING_D
export function audiLogoSVG(color: string): string {
  const paint = color || '#FFFFFF'
  const r = (RING_D - RING_STROKE) / 2
  const rings = [0, 1, 2, 3]
    .map(i => `<circle cx="${RING_D / 2 + i * RING_GAP}" cy="${RING_D / 2}" r="${r}"/>`)
    .join('')
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 325 100" width="325" height="100" preserveAspectRatio="xMidYMid meet" fill="none" stroke="${paint}" stroke-width="${RING_STROKE}">${rings}</svg>`
}
// 给定宽度，按真实比例算出高度，避免被拉成椭圆。
export function audiLogoSize(width: number) {
  return { width: Math.round(width), height: Math.round(width / AUDI_LOGO_RATIO) }
}

