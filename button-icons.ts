// 每个图标 24×24 视框、圆角端点，黑白通用。
// 尺寸统一规则：每枚图标的「几何外框 + 1.7 描边」按最长边归一到 17 单位并居中到 (12,12)，
// 因此所有图标看起来一样大。线宽默认 1.7，可由设置里的「图标线条粗细」改写
// （四个尺寸各存一份数值；线宽变化时外框仍按 1.7 基准归一，视觉大小基本不变）。
// 例外：尾门 / 车窗 / 空调 / 冷车 / 座椅加热是实心图形（无描边、纯 fill），不走 wrap 的描边模板，
// 见 TRUNK_VIEWBOX / WINDOW_VIEWBOX / AC_VIEWBOX / COOL_VIEWBOX / SEAT_VIEWBOX 与 buttonIconSVG 里的特判。

// 描边模板：lineWidth 由调用方传入（设置里的「图标线条粗细」），默认 1.7。
// tight=true：把 24 视框裁到图形实际包围盒（归一后的 17 单位 + 描边），
// 让图形铺满整个方框 —— 告警行这类小尺寸图标要和 SF Symbol 视觉齐平就用它；
// 按钮里仍用 24 视框（留白是按钮图标设计的一部分，不能变）。
function wrap(color: string, body: string, lineWidth = 1.7, tight = false): string {
  const width = Number.isFinite(lineWidth) ? lineWidth : 1.7
  // 再留 10% 余量：SF Symbol 在 frame 里自带一圈内边距，描边图标也留同样比例，两者视觉尺寸才齐平。
  const box = tight ? (17 + Math.max(width, 1.7)) * 1.1 : 24
  const origin = tight ? (24 - box) / 2 : 0
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${origin} ${origin} ${box} ${box}" width="24" height="24" fill="none" stroke="${color}" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`
}
function dot(color: string, cx: number, cy: number, r: number): string {
  return `<circle cx="${cx}" cy="${cy}" r="${r}" fill="${color}" stroke="none"/>`
}

